#!/usr/bin/env node

import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, realpath, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build, version as esbuildVersion } from "esbuild";

const repoRoot = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const fixtureRoot = path.join(
  repoRoot,
  "packages/client/src/components/__tests__/fixtures/operator-voice",
);
const fixturePackage = path.join(fixtureRoot, "pi-extensions/pi-operator-voice");
const bundlePath = path.join(fixturePackage, "src/operator-delivery.mjs");
const fixtureLexiconPath = path.join(fixturePackage, "operator-lexicon.json");
const manifestPath = path.join(fixtureRoot, "fixture-manifest.json");
const producerPackagePath = "pi-extensions/pi-operator-voice";
const producerSourcePath = `${producerPackagePath}/src/operator-delivery.ts`;
const producerLexiconPath = `${producerPackagePath}/operator-lexicon.json`;

function usage() {
  return [
    "Usage:",
    "  node scripts/generate-operator-voice-test-fixture.mjs \\",
    "    --producer-worktree <path> --source-commit <sha> [--check]",
  ].join("\n");
}

function argument(name) {
  const index = process.argv.indexOf(name);
  if (index < 0 || !process.argv[index + 1] || process.argv[index + 1].startsWith("--")) {
    throw new Error(`Missing ${name}\n\n${usage()}`);
  }
  return process.argv[index + 1];
}

function git(worktree, args) {
  return execFileSync("git", ["-C", worktree, ...args], { encoding: "utf8" }).trim();
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

const producerWorktree = await realpath(argument("--producer-worktree"));
const requestedCommit = argument("--source-commit");
const checkOnly = process.argv.includes("--check");
const sourceCommit = git(producerWorktree, ["rev-parse", `${requestedCommit}^{commit}`]);
const producerPackageRoot = path.join(producerWorktree, producerPackagePath);
const sourceFile = path.join(producerWorktree, producerSourcePath);
const lexiconFile = path.join(producerWorktree, producerLexiconPath);

const relevantPaths = [
  `${producerPackagePath}/src`,
  producerLexiconPath,
];
const diff = spawnSync(
  "git",
  ["-C", producerWorktree, "diff", "--quiet", sourceCommit, "--", ...relevantPaths],
  { encoding: "utf8" },
);
if (diff.status !== 0) {
  throw new Error(
    `Producer source differs from ${sourceCommit}. Check out that revision or choose the matching source commit.`,
  );
}
const untracked = git(producerWorktree, [
  "status",
  "--porcelain",
  "--untracked-files=all",
  "--",
  ...relevantPaths,
]);
if (untracked) {
  throw new Error(`Producer fixture inputs are dirty:\n${untracked}`);
}

const source = await readFile(sourceFile);
const lexicon = await readFile(lexiconFile);
const sourceTreeObject = git(producerWorktree, [
  "rev-parse",
  `${sourceCommit}:${producerPackagePath}/src`,
]);
const sourceSha256 = sha256(source);
const lexiconSha256 = sha256(lexicon);
const banner = [
  "/* Generated by scripts/generate-operator-voice-test-fixture.mjs.",
  ` * Producer commit: ${sourceCommit}`,
  ` * Producer source: ${producerSourcePath}`,
  ` * Source SHA-256: ${sourceSha256}`,
  " * Do not edit this bundle by hand.",
  " */",
].join("\n");
const result = await build({
  absWorkingDir: producerPackageRoot,
  stdin: {
    contents: 'export { materializeOperatorDelivery } from "./src/operator-delivery.ts";',
    loader: "ts",
    resolveDir: producerPackageRoot,
    sourcefile: "fixture-entry.ts",
  },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  treeShaking: true,
  legalComments: "none",
  sourcemap: false,
  minify: false,
  write: false,
  outfile: "operator-delivery.mjs",
  banner: { js: banner },
  plugins: [{
    name: "fixture-unused-provider-binding",
    setup(context) {
      context.onResolve(
        { filter: /^@earendil-works\/pi-ai\/compat$/ },
        () => ({ path: "pi-ai-compat", namespace: "fixture-stub", sideEffects: false }),
      );
      context.onLoad(
        { filter: /.*/, namespace: "fixture-stub" },
        () => ({
          contents: "export async function complete() { throw new Error('Provider binding is outside this materialize-only fixture'); }",
          loader: "js",
        }),
      );
    },
  }],
});
const bundle = result.outputFiles[0].contents;
const manifest = {
  schemaVersion: 1,
  sourceRepository: "pi-config",
  sourceCommit,
  sourceTreeObject,
  sourcePath: producerSourcePath,
  sourceSha256,
  lexiconPath: producerLexiconPath,
  lexiconSha256,
  bundlePath: "pi-extensions/pi-operator-voice/src/operator-delivery.mjs",
  bundleSha256: sha256(bundle),
  bundledExport: "materializeOperatorDelivery",
  providerBinding: "excluded as unused by the materialize-only entry",
  generatorPath: "scripts/generate-operator-voice-test-fixture.mjs",
  esbuildVersion,
};
const manifestBytes = Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`);

if (checkOnly) {
  const expectedBundle = await readFile(bundlePath);
  const expectedLexicon = await readFile(fixtureLexiconPath);
  const expectedManifest = await readFile(manifestPath);
  if (!expectedBundle.equals(bundle) ||
      !expectedLexicon.equals(lexicon) ||
      !expectedManifest.equals(manifestBytes)) {
    throw new Error("Operator-voice fixture is stale; regenerate it without --check.");
  }
  console.log(`Operator-voice fixture matches ${sourceCommit}.`);
} else {
  await mkdir(path.dirname(bundlePath), { recursive: true });
  await writeFile(bundlePath, bundle);
  await writeFile(fixtureLexiconPath, lexicon);
  await writeFile(manifestPath, manifestBytes);
  console.log(`Generated operator-voice fixture from ${sourceCommit}.`);
}
